        tests/test_wifi_profiles.c os/services/network/wifi_profiles.c -o "${test_dir}/test_wifi_profiles"
    "${test_dir}/test_wifi_profiles"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Ios/services/network \
        tests/test_wifi_setup_qr.c os/services/network/wifi_setup_qr.c -o "${test_dir}/test_wifi_setup_qr"
    "${test_dir}/test_wifi_setup_qr"
