        actionlint_bin="$(command -v actionlint || true)"
    fi
    if [[ -z "${actionlint_bin}" || ! -x "${actionlint_bin}" ]]; then
        actionlint_bin="$(./tools/install-actionlint.sh)"
    fi
    "${actionlint_bin}" -color .github/workflows/*.yml

    test_dir="$(mktemp -d /tmp/ai-passport-host-tests.XXXXXX)"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Imain \
        tests/test_ui_pixel_math.c main/ui_pixel_math.c \
        -o "${test_dir}/test_ui_pixel_math"
    "${test_dir}/test_ui_pixel_math"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Imain \
        tests/test_demo_navigation.c main/demo_navigation.c \
        -o "${test_dir}/test_demo_navigation"
    "${test_dir}/test_demo_navigation"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Imain \
        tests/test_key_guard.c -o "${test_dir}/test_key_guard"
    "${test_dir}/test_key_guard"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Ios/services/clock \
        tests/test_alarm.c os/services/clock/alarm.c -o "${test_dir}/test_alarm"
    "${test_dir}/test_alarm"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Ios/services/settings \
        tests/test_settings_list.c os/services/settings/list.c \
        -o "${test_dir}/test_settings_list"
    "${test_dir}/test_settings_list"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Ios/services/audio \
        tests/test_volume.c os/services/audio/volume.c -o "${test_dir}/test_volume"
    "${test_dir}/test_volume"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror \
        tests/test_app_version.c os/services/storage/app_version.c \
        -o "${test_dir}/test_app_version"
    "${test_dir}/test_app_version"
    "${CC:-cc}" -std=c11 -Wall -Wextra -Werror -Ios/services/network \
        tests/test_wifi_setup_form.c os/services/network/wifi_setup_form.c \
        -o "${test_dir}/test_wifi_setup_form"
    "${test_dir}/test_wifi_setup_form"
