"""Rebuild the deterministic gzip portal asset (standard library only)."""
from pathlib import Path
import gzip
ROOT = Path(__file__).resolve().parents[2]
source = ROOT/'os/services/network/wifi_setup_page.html'
blob = gzip.compress(source.read_bytes(), compresslevel=9, mtime=0)
output = ROOT/'os/services/network/wifi_setup_page.inc'
output.write_text('/* Generated by tools/passport/build_wifi_setup_page.py; edit .html. */\n'+
                  ''.join(','.join(f'0x{x:02x}' for x in blob[i:i+16])+',\n'
                          for i in range(0,len(blob),16)))
print(f'Wi-Fi portal gzip: {source.stat().st_size} -> {len(blob)} bytes')
