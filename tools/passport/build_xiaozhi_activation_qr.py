#!/usr/bin/env python3
"""Generate a fixed console QR using the pinned LVGL QR encoder (host build)."""
import argparse
from pathlib import Path
import subprocess
import tempfile
ROOT=Path(__file__).resolve().parents[2]
URL='https://xiaozhi.me/console/'
def generate(output):
    source=ROOT/'managed_components/lvgl__lvgl/src/libs/qrcode'
    if not (source/'qrcodegen.c').is_file():raise ValueError('resolve pinned LVGL with ESP-IDF first')
    with tempfile.TemporaryDirectory() as tmp:
        tmp=Path(tmp);program=tmp/'qr.c'
        program.write_text('#include "qrcodegen.h"\n#include <stdio.h>\nint main(void){uint8_t temp[qrcodegen_BUFFER_LEN_MAX],qr[qrcodegen_BUFFER_LEN_MAX];\n'
            'if(!qrcodegen_encodeText("'+URL+'",temp,qr,qrcodegen_Ecc_LOW,1,2,qrcodegen_Mask_AUTO,false))return 1;\n'
            'int n=qrcodegen_getSize(qr);printf("%d\\n",n);for(int y=0;y<n;y++){for(int x=0;x<n;x++)putchar(qrcodegen_getModule(qr,x,y)?\'1\':\'0\');putchar(\'\\n\');}return 0;}\n')
        subprocess.run(['cc','-std=c11','-DLV_CONF_SKIP','-DLV_USE_QRCODE=1','-I'+str(source),str(program),str(source/'qrcodegen.c'),'-o',str(tmp/'qr')],check=True)
        rows=subprocess.check_output([str(tmp/'qr')],text=True).splitlines();size=int(rows[0]);runs=[]
        for y,row in enumerate(rows[1:]):
            x=0
            while x<size:
                if row[x]=='0':x+=1;continue
                start=x
                while x<size and row[x]=='1':x+=1
                runs.append((y,start,x-start))
    if len(runs)+2>192:raise ValueError('QR exceeds Native draw-command budget')
    header='#pragma once\n/* Generated by tools/passport/build_xiaozhi_activation_qr.py; LVGL 9.5.0 QR encoder.\n * Fixed public URL only; no activation code or device identity. */\n'
    header+='#define XIAOZHI_ACTIVATION_URL "'+URL+'"\n'
    header+='#define XIAOZHI_QR_MODULES '+str(size)+'\n'
    header+='static const unsigned char activation_qr_runs[][3] = {\n'+''.join('  {%d,%d,%d},\n'%r for r in runs)+'};\n'
    Path(output).write_text(header)
    print('Activation QR:',size,'modules,',len(runs),'runs,',len(runs)*3,'data bytes')
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',default=str(ROOT/'examples/xiaozhi_native/activation_qr.h'));a=p.parse_args();generate(a.output)
