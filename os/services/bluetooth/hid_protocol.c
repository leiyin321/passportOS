#include "hid_protocol.h"
/* HOGP input report 1: 3 buttons + padding, relative signed X/Y/wheel.
 * Report 2: one 16-bit Consumer Control usage; zero releases all controls. */
const uint8_t ps_hid_report_map[]={
  0x05,0x01,0x09,0x02,0xa1,0x01,0x85,0x01,0x09,0x01,0xa1,0x00,
  0x05,0x09,0x19,0x01,0x29,0x03,0x15,0x00,0x25,0x01,0x95,0x03,0x75,0x01,0x81,0x02,
  0x95,0x01,0x75,0x05,0x81,0x03,0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,
  0x15,0x81,0x25,0x7f,0x75,0x08,0x95,0x03,0x81,0x06,0xc0,0xc0,
  0x05,0x0c,0x09,0x01,0xa1,0x01,0x85,0x02,0x15,0x00,0x26,0xff,0x03,
  0x19,0x00,0x2a,0xff,0x03,0x75,0x10,0x95,0x01,0x81,0x00,0xc0
};
const size_t ps_hid_report_map_size=sizeof(ps_hid_report_map);
bool ps_hid_report_valid(unsigned id,const void *data,size_t n) {
  if(!data)return false;
  const uint8_t *p=data;
  if(id==1)return n==4 && !(p[0]&~7u) && p[1]!=128 && p[2]!=128 && p[3]!=128;
  if(id!=2 || n!=2)return false;
  unsigned usage=p[0]|((unsigned)p[1]<<8);
  return !usage || usage==0xb5 || usage==0xb6 || usage==0xcd || usage==0xe2 || usage==0xe9 || usage==0xea;
}
